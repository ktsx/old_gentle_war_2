export const GLYPH_W = 5, GLYPH_H = 7;

/** Draw text (upper-cased; unknown characters become '?') with the top-left corner at (x, y). Returns the width drawn. */
export function drawText(img: Image32, x: number, y: number, text: string, color: RGBA, scale = 1, spacing = 1): number {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const rows = G[ch] ?? G["?"];
    for (let r = 0; r < GLYPH_H; r++) for (let c = 0; c < GLYPH_W; c++) {
      if (rows[r] & (0x10 >> c)) img.fillRect(cx + c * scale, y + r * scale, scale, scale, color);
    }
    cx += (GLYPH_W + spacing) * scale;
  }
  return cx - x;
}

export function textWidth(text: string, scale = 1, spacing = 1): number {
  return text.length * (GLYPH_W + spacing) * scale - spacing * scale;
}

/** Split a CamelCase / snake_case identifier into words that fit `maxChars` per line (greedy). */
export function wrapName(name: string, maxChars: number, maxLines: number): string[] {
  const words = name.replace(/[_\-]+/g, " ").replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2").split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let cur = "";
  for (const w of words) {
    if (!cur) cur = w;
    else if ((cur + " " + w).length <= maxChars) cur += " " + w;
    else { lines.push(cur); cur = w; }
    while (cur.length > maxChars) { lines.push(cur.slice(0, maxChars)); cur = cur.slice(maxChars); }
  }
  if (cur) lines.push(cur);
  if (lines.length > maxLines) { lines.length = maxLines; lines[maxLines - 1] = lines[maxLines - 1].slice(0, maxChars - 1) + "."; }
  return lines;
}
